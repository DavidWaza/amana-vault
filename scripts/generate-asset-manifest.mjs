import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const assetsDir = path.join(root, "public", "assets");
const lifestyleDir = path.join(assetsDir, "lifestyle");
const ambienceDir = path.join(assetsDir, "ambience");
const outFile = path.join(
  root,
  "app",
  "components",
  "client-dashboard",
  "build-journey",
  "generated-asset-manifest.ts",
);

const IMAGE_EXT = /\.(png|jpe?g|webp)$/i;

/** Root asset filename → home-type option id */
const HOME_FILE_ALIASES = {
  duplex: "duplex",
  bungalow: "bungalow",
  "investment-property": "investment",
  "multi-family": "multi_family",
  "duplex-suplex": "duplexSuplex",
  villa: "villa",
  apartments: "apartments",
  apartment: "apartments",
};

/** Filename (no ext) → style option id */
const STYLE_FILE_ALIASES = {
  "modern-tropical": "modern_tropical",
  "afro-modern": "afro_modern",
  "contemporary-luxury": "contemporary_luxury",
  "luxury-contemporary": "contemporary_luxury",
  "classic-nigerian": "classic_nigerian",
  "eco-friendly": "eco_friendly",
};

function listImages(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((name) => IMAGE_EXT.test(name))
    .sort((a, b) => a.localeCompare(b));
}

function normalizeKey(filename) {
  return path
    .basename(filename, path.extname(filename))
    .toLowerCase()
    .replace(/\s+/g, "-");
}

function buildManifest() {
  const homeTypes = {};
  const styles = {};
  let hero = "";

  for (const file of listImages(assetsDir)) {
    const key = normalizeKey(file);
    const optionId = HOME_FILE_ALIASES[key];
    if (optionId) {
      homeTypes[optionId] = `/assets/${file}`;
    }
  }

  const scanFolder = (dir, urlPrefix, { overwrite = false } = {}) => {
    for (const file of listImages(dir)) {
      const key = normalizeKey(file);
      if (key === "hero") {
        if (overwrite || !hero) hero = `${urlPrefix}/${file}`;
        continue;
      }
      const styleId = STYLE_FILE_ALIASES[key];
      if (styleId && (overwrite || !styles[styleId])) {
        styles[styleId] = `${urlPrefix}/${file}`;
      }
      const homeId = HOME_FILE_ALIASES[key];
      if (homeId && (overwrite || !homeTypes[homeId])) {
        homeTypes[homeId] = `${urlPrefix}/${file}`;
      }
    }
  };

  // Lifestyle first, then ambience overrides (preferred for style cards).
  scanFolder(lifestyleDir, "/assets/lifestyle");
  scanFolder(ambienceDir, "/assets/ambience", { overwrite: true });

  return { homeTypes, styles, hero };
}

const manifest = buildManifest();

const contents = `/* eslint-disable */
/** Auto-generated by scripts/generate-asset-manifest.mjs — do not edit manually. */
export const GENERATED_ASSET_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;
`;

fs.writeFileSync(outFile, contents, "utf8");
console.log("Wrote asset manifest:", outFile);
console.log("Home types:", Object.keys(manifest.homeTypes).join(", ") || "(none)");
console.log("Styles:", Object.keys(manifest.styles).join(", ") || "(none)");
console.log("Hero:", manifest.hero || "(none)");
